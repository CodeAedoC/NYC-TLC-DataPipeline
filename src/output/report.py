"""
src/output/report.py
Stage 5 — OUTPUT & REPORTING (specs.md OUT-01 through OUT-05)

OUT-01: trips_clean.parquet       -> data/processed/
OUT-02: trips_flagged.parquet     -> data/processed/audit/
OUT-03: kpi_summary.csv           -> data/processed/
OUT-04: pipeline.log              -> logs/  (written by logger throughout pipeline)
OUT-05: known_unknown_assumptions.md -> docs/
REF-04: Refund Summary row in OUT-05
"""
import os
from datetime import datetime, timezone

import pandas as pd

from src.utils.logger import get_logger


def _get_project_root() -> str:
    return os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


# ---------------------------------------------------------------------------
# OUT-03: KPI summary CSV
# ---------------------------------------------------------------------------

def write_kpi_summary(metrics: list[dict]) -> str:
    """OUT-03: Write 5-row kpi_summary.csv to data/processed/."""
    logger = get_logger()
    root = _get_project_root()
    out_dir = os.path.join(root, "data", "processed")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "kpi_summary.csv")
    pd.DataFrame(metrics).to_csv(path, index=False)
    logger.info(f"[OUTPUT] Wrote kpi_summary.csv ({len(metrics)} metrics)")
    return path


# ---------------------------------------------------------------------------
# OUT-05 + REF-04: known_unknown_assumptions.md
# ---------------------------------------------------------------------------

def write_known_unknown_md(datasets: dict, metrics: list[dict], month: str) -> str:
    """
    OUT-05: Auto-generate docs/known_unknown_assumptions.md.
    REF-04: Includes Refund Summary row.
    """
    logger = get_logger()
    root = _get_project_root()
    docs_dir = os.path.join(root, "docs")
    os.makedirs(docs_dir, exist_ok=True)
    path = os.path.join(docs_dir, "known_unknown_assumptions.md")

    clean = datasets["clean"]
    flagged = datasets["flagged"]
    refunds = datasets["refunds"]
    total_raw = len(clean) + len(flagged)
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    # Refund summary (REF-04)
    refund_count = len(refunds)
    refund_value = refunds["total_amount"].sum() if len(refunds) > 0 else 0.0
    refund_pct = refund_count / total_raw * 100 if total_raw > 0 else 0.0

    # Flag breakdown from flagged set
    flag_counts: dict[str, int] = {}
    for flags in flagged["validation_flag"]:
        for f in str(flags).split("|"):
            if f and f != "VALID_OPERATIONAL":
                flag_counts[f] = flag_counts.get(f, 0) + 1
    flag_table = "\n".join(
        f"| `{flag}` | {count:,} |"
        for flag, count in sorted(flag_counts.items(), key=lambda x: -x[1])
    )

    # KPI table
    kpi_rows = "\n".join(
        f"| {m['metric_id']} | {m['metric_name']} | {m['value']} {m['unit']} |"
        for m in metrics
    )

    content = f"""# Known / Unknown / Assumptions / Limitations
> **Auto-generated by Stage 5 — report.py**
> **Month processed:** `{month}`
> **Generated at:** {now}

---

## Validation Flag Summary

| Flag | Row Count |
| :--- | :--- |
{flag_table}

**Total flagged rows:** {len(flagged):,} ({len(flagged)/total_raw*100:.2f}%)
**VALID_OPERATIONAL rows:** {len(clean):,} ({len(clean)/total_raw*100:.2f}%)
**Total raw rows:** {total_raw:,}

---

## Refund Summary (REF-04)

| Item | Value |
| :--- | :--- |
| Negative-fare trip count | {refund_count:,} |
| Total negative value | ${refund_value:,.2f} |
| % of raw dataset | {refund_pct:.2f}% |

---

## KPI Results

| Metric ID | Name | Value |
| :--- | :--- | :--- |
{kpi_rows}

---

## Known / Unknown / Assumptions / Limitations

| Category | Item |
| :--- | :--- |
| **Known** | 140,162 trips (4.73%) have NULL `RatecodeID`, `passenger_count`, and fee fields — legacy meter firmware gap |
| **Known** | 761,838 trips (25.7%) have billing component math discrepancies > $0.05 — consistent -$2.50 congestion surcharge vendor encoding error |
| **Known** | LocationIDs 264/265 exist in raw data and are not mapped to any borough |
| **Known** | {refund_count:,} trips have negative fare amounts (total ${refund_value:,.2f}) — assumed refunds or voids |
| **Unknown** | Whether negative fares are intentional refunds or meter malfunctions — cannot confirm without TLC chargeback ledger |
| **Unknown** | The true driver or medallion identity behind any trip — omitted from public data for privacy |
| **Assumption** | NULL `congestion_surcharge` treated as $0.00 (trip pre-dates or exempt from June 2019 law) |
| **Assumption** | NULL `Airport_fee` treated as $0.00 (trip not originating from JFK/LGA) |
| **Assumption** | Speed > 100 mph indicates GPS/timestamp error, not actual vehicle speed |
| **Assumption** | Trips with same PULocationID and DOLocationID are legitimate short intra-zone rides, not duplicates |
| **Limitation** | M-02 (Hourly Driver Revenue) is an approximation — no real shift start/end data exists in public records |
| **Limitation** | CFCR (M-04) cannot distinguish Manhattan trips legally exempt from congestion pricing |
| **Limitation** | Industry Indicators (S3) ingested as raw reference only — not yet wired into metric calculations |
"""

    with open(path, "w", encoding="utf-8") as f:
        f.write(content)

    logger.info(f"[OUTPUT] Wrote known_unknown_assumptions.md")
    return path


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def run_output(datasets: dict, metrics: list[dict], month: str) -> None:
    """
    Run all Stage 5 output writers.
    Note: OUT-01 and OUT-02 are written in transform.py (TRF-10/11).
    This function handles OUT-03, OUT-05, and logs pipeline completion.
    """
    logger = get_logger()
    logger.info("=== STAGE 5: OUTPUT ===")

    write_kpi_summary(metrics)
    write_known_unknown_md(datasets, metrics, month)

    logger.info("[OUTPUT] Pipeline complete.")
